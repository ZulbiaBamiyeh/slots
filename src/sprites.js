const DJINN_COLS = {
  blue: ['#3A5FE0', '#7FA8FF'], pink: ['#E0609A', '#FFB0D0'], gold: ['#D9922A', '#FFD84A'], red: ['#D8343C', '#FF8A6A'],
};

function rows(src) { return src.trim().split('\n').map((r) => r.trimEnd()); }

function bake(src, w, h, pal, outline = true) {
  const rs = rows(src);
  const cv = document.createElement('canvas'); cv.width = w; cv.height = h;
  const g = cv.getContext('2d');
  const at = (x, y) => (y >= 0 && y < rs.length && x >= 0 && x < (rs[y] || '').length && rs[y][x] !== '.' ? rs[y][x] : null);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const ch = at(x, y);
    if (ch) { g.fillStyle = pal[ch] || '#f0f'; g.fillRect(x, y, 1, 1); }
    else if (outline && (at(x - 1, y) || at(x + 1, y) || at(x, y - 1) || at(x, y + 1))) { g.fillStyle = NAVY; g.fillRect(x, y, 1, 1); }
  }
  return cv;
}

const cache = new Map();
export function sprite(id) {
  let c = cache.get(id);
  if (!c) { c = bake(RAW[id] || RAW.lock, 16, 16, PAL); cache.set(id, c); }
  return c;
}
// Solid single-colour silhouette (for flashes and glows)
export function silhouette(id, col) {
  const key = id + '|' + col;
  let c = cache.get(key);
  if (!c) {
    const s = sprite(id);
    c = document.createElement('canvas'); c.width = 16; c.height = 16;
    const g = c.getContext('2d');
    g.drawImage(s, 0, 0); g.globalCompositeOperation = 'source-in'; g.fillStyle = col; g.fillRect(0, 0, 16, 16);
    cache.set(key, c);
  }
  return c;
}
export const DJ_W = 24, DJ_H = 32;
export function djinnSprite(kind = 'blue') {
  const key = 'djinn|' + kind;
  let c = cache.get(key);
  if (!c) {
    const [b, B] = DJINN_COLS[kind] || DJINN_COLS.blue;
    c = bake(DJINN, DJ_W, DJ_H, { ...PAL, b, B });
    cache.set(key, c);
  }
  return c;
}
